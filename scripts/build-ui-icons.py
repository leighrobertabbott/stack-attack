"""Pack food and interface artwork into a bundled canvas icon atlas."""

import base64
import io
import json
from pathlib import Path
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TILE_SIZE = 72
COLUMNS = 8


def main():
    output = subprocess.check_output(
        [
            "node",
            "--input-type=module",
            "-e",
            """
            import { FILLED } from './dist/stages.js';
            import { UPGRADES, MEDALS } from './dist/service.js';
            const perks = UPGRADES.map(({ icon }) => icon);
            const medals = MEDALS.filter(Boolean).map(name => 'medal-' + name.toLowerCase());
            console.log(JSON.stringify([...Object.keys(FILLED), ...perks, ...medals]));
            """,
        ],
        cwd=ROOT,
        text=True,
    )
    kinds = [*json.loads(output), "flip", "order-ticket", "sandwich", "gold-star", "pin", "funk"]
    rows = (len(kinds) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * TILE_SIZE, rows * TILE_SIZE))
    for index, kind in enumerate(kinds):
        with Image.open(ROOT / "dist" / "art" / f"{kind}.webp") as source:
            icon = source.convert("RGBA")
            icon.thumbnail((TILE_SIZE, TILE_SIZE), Image.Resampling.LANCZOS)
            x = (index % COLUMNS) * TILE_SIZE + (TILE_SIZE - icon.width) // 2
            y = (index // COLUMNS) * TILE_SIZE + (TILE_SIZE - icon.height) // 2
            atlas.paste(icon, (x, y))

    data = io.BytesIO()
    atlas.save(data, "WEBP", quality=88, method=6)
    payload = base64.b64encode(data.getvalue()).decode("ascii")
    (ROOT / "dist" / "ui-icon-data.js").write_text(
        "// Generated by scripts/build-ui-icons.py.\n"
        f"export const kinds = {json.dumps(kinds)};\n"
        f"export const tileSize = {TILE_SIZE};\n"
        f"export const columns = {COLUMNS};\n"
        f"export const atlas = '{payload}';\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
